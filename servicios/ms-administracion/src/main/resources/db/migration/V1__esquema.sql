-- Base de ms-administracion (ms_administracion): la bitácora de auditoría y los parámetros del sistema.

-- La bitácora (Bitacora / RegistroAuditoria de la 4e): lo que llega por auditoria.evento de los demás servicios y
-- lo que ms-administracion registra directo (nota n_bitacora). correlacion_id es el recorrido (DEC-64); un evento
-- que Kafka entrega dos veces no se repite (mismos datos y misma correlación).
CREATE TABLE auditoria (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accion         VARCHAR(500) NOT NULL,
    usuario        VARCHAR(160) NOT NULL,
    fecha          DATE NOT NULL,
    hora           TIME NOT NULL,
    correlacion_id UUID
);
CREATE INDEX auditoria_fecha ON auditoria (fecha, hora);
CREATE UNIQUE INDEX auditoria_unica ON auditoria (fecha, hora, usuario, accion, correlacion_id) NULLS NOT DISTINCT;

-- Los parámetros del sistema (ParametrosRepositoryPort): ParametrosSistema es su caché en cada réplica.
-- Los del tema los lee la SPA al iniciar sesión (GET /api/admin/parametros/tema, DEC-86).
CREATE TABLE parametro (
    clave       VARCHAR(80) PRIMARY KEY,
    valor       TEXT NOT NULL,
    actualizado TIMESTAMP NOT NULL DEFAULT now()
);
