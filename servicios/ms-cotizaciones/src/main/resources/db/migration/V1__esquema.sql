-- ── Cotizaciones (V13–V19) ─────────────────────────────────────────────────────────────────────
-- Los números siguen a los de la demo: la primera cotización es COT-018 (como SOL-031 en ms-solicitudes).
CREATE SEQUENCE cotizacion_numero START WITH 18;

CREATE TABLE cotizacion (
    numero       VARCHAR(20) PRIMARY KEY,
    proveedor_id BIGINT NOT NULL REFERENCES proveedor (id),
    fecha_envio  DATE NOT NULL,
    fecha_limite DATE NOT NULL,
    pdf_url      VARCHAR(255),
    estado       VARCHAR(20) NOT NULL
);
CREATE INDEX cotizacion_estado ON cotizacion (estado, numero);
CREATE INDEX cotizacion_proveedor ON cotizacion (proveedor_id);

-- Una cotización agrupa una o varias solicitudes (HU-09, DEC-05).
CREATE TABLE cotizacion_solicitud (
    cotizacion_numero VARCHAR(20) NOT NULL REFERENCES cotizacion (numero) ON DELETE CASCADE,
    orden             INT NOT NULL,
    solicitud_numero  VARCHAR(20) NOT NULL,
    PRIMARY KEY (cotizacion_numero, orden)
);
CREATE INDEX cotizacion_solicitud_numero ON cotizacion_solicitud (solicitud_numero);

-- Los precios son por unidad: el del Ministerio (al generar) y el del proveedor (V18).
CREATE TABLE item_cotizacion (
    cotizacion_numero VARCHAR(20) NOT NULL REFERENCES cotizacion (numero) ON DELETE CASCADE,
    orden             INT NOT NULL,
    producto_id       BIGINT NOT NULL,
    cantidad          NUMERIC(12, 3) NOT NULL CHECK (cantidad > 0),
    unidad            VARCHAR(20) NOT NULL,
    precio_estandar   NUMERIC(12, 2),
    precio_proveedor  NUMERIC(12, 2),
    PRIMARY KEY (cotizacion_numero, orden)
);

-- Copia del nombre de cada producto, tal como venía al generar la cotización (lo pone la SPA desde
-- ms-menu): el PDF para el proveedor y las ventanas del director lo muestran sin llamar a ms-menu (DEC-74).
CREATE TABLE producto_nombre (
    producto_id BIGINT PRIMARY KEY,
    nombre      VARCHAR(80) NOT NULL
);
