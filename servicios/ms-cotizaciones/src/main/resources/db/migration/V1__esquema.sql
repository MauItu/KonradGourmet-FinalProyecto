-- Base de ms-cotizaciones (ms_cotizaciones). Ningún otro servicio la lee: ms-solicitudes, ms-notificaciones,
-- ms-ordenes y ms-analitica reciben cada cotización por cotizacion.enviada y cotizacion.validada.

-- ── Proveedores (HU-15) ────────────────────────────────────────────────────────────────────────
CREATE TABLE proveedor (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social VARCHAR(120) NOT NULL,
    nit          VARCHAR(30)  NOT NULL UNIQUE,
    correo       VARCHAR(160) NOT NULL,
    telefono     VARCHAR(30),
    direccion    VARCHAR(160),
    activo       BOOLEAN NOT NULL
);

CREATE TABLE proveedor_categoria (
    proveedor_id BIGINT NOT NULL REFERENCES proveedor (id) ON DELETE CASCADE,
    orden        INT NOT NULL,
    categoria    VARCHAR(60) NOT NULL,
    PRIMARY KEY (proveedor_id, orden)
);

