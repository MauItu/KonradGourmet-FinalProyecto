-- Cada envío y cada fallo (nota n_fallos de la 4d), con la correlación del recorrido (DEC-64): V14 la usa para
-- saber si el correo al proveedor ya salió (DEC-76).
CREATE TABLE envio (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destino        VARCHAR(160) NOT NULL,
    tipo           VARCHAR(40) NOT NULL,
    fecha_hora     TIMESTAMP NOT NULL,
    exito          BOOLEAN NOT NULL,
    error          VARCHAR(500),
    correlacion_id UUID
);
CREATE INDEX envio_correlacion ON envio (correlacion_id);
