-- Base de ms-notificaciones (ms_notificaciones): la libreta de destinatarios y la traza de los envíos.

-- Los jefes de cocina de cada sucursal, que reciben la alarma y el correo de stock bajo (y en el corte 6 las
-- promociones). La carga el administrador (DestinatarioRestController); hasta que exista su ventana (corte 6)
-- empieza con el jefe de la demo en la Sucursal Centro.
CREATE TABLE destinatario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sucursal_id BIGINT NOT NULL,
    correo      VARCHAR(160) NOT NULL,
    UNIQUE (sucursal_id, correo)
);
